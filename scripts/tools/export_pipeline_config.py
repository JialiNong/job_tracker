#!/usr/bin/env python3
"""
Export the pipeline settings the TypeScript API sources share with the
Python browser scrapers, from src/core/config.py (the one place to edit
them) to packages/pipeline/src/config.generated.json.

    PYTHONPATH=src python3 scripts/tools/export_pipeline_config.py          # write
    PYTHONPATH=src python3 scripts/tools/export_pipeline_config.py --check  # exit 1 if stale

tests/test_pipeline_config_export.py runs --check, so editing config.py
without re-exporting fails the unit tests.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from core import config

OUT = Path(__file__).resolve().parents[2] / "packages/pipeline/src/config.generated.json"
NAMES = [
    "DEFAULT_KEYWORDS",
    "TITLE_AUTO_PASS_KEYWORDS",
    "TITLE_EXCLUDE_KEYWORDS",
    "FEED_TITLE_INCLUDE_PATTERNS",
    "API_TITLE_EXCLUDE_EXTRA",
    "API_MAX_POSTING_AGE_DAYS",
    "ARBEITSAGENTUR_CONFIG",
    "ARBEITNOW_CONFIG",
    "ADZUNA_CONFIG",
    "ATS_CONFIG",
    # Browser scraper run (pnpm pipeline run)
    "FULL_MAX_PAGES",
    "INDEED_JOBS_PER_PAGE",
    "LINKEDIN_JOBS_PER_PAGE",
    "CDP_HOST",
    "CDP_PORT",
    "CHROME_BIN",
    "CHROME_USER_DATA_DIR",
]


def exported() -> str:
    data = {"_comment": "Generated by scripts/tools/export_pipeline_config.py from src/core/config.py. Do not edit."}
    data.update({name: getattr(config, name) for name in NAMES})
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    text = exported()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run PYTHONPATH=src python3 scripts/tools/export_pipeline_config.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
